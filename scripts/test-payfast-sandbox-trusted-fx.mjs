import assert from 'node:assert/strict';
import {issueTrustedSandboxFxQuote} from '../functions/_lib/payfast-sandbox-trusted-fx.js';
const now=Date.parse('2026-11-21T12:00:00Z');
const endpoint='https://fx.example.org/rates';
const makeProvider=(payload)=>async()=>new Response(JSON.stringify(payload),{headers:{'content-type':'application/json'}});
const good={base:'USD',quote:'ZAR',rate:18.25,asOf:'2026-11-20'};
const args={plan:'monthly',nowMs:now,fxEndpoint:endpoint,fetchImpl:makeProvider(good),reference:'fxref_12345678'};
let result=await issueTrustedSandboxFxQuote(args);
assert.equal(result.ok,true);
assert.equal(result.quote.usdMinor,899);
assert.equal(result.quote.zarMinor,16407);
assert.equal(result.quote.source,'server_verified');
result=await issueTrustedSandboxFxQuote({...args,plan:'annual'});
assert.equal(result.ok,true);
assert.equal(result.quote.usdMinor,8999);
result=await issueTrustedSandboxFxQuote({...args,fxEndpoint:'http://fx.example.org/rates'});
assert.equal(result.ok,false);
result=await issueTrustedSandboxFxQuote({...args,fetchImpl:makeProvider({...good,asOf:'2026-10-01'})});
assert.equal(result.ok,false);
result=await issueTrustedSandboxFxQuote({...args,fetchImpl:makeProvider({...good,quote:'EUR'})});
assert.equal(result.ok,false);
let attempts=0;
result=await issueTrustedSandboxFxQuote({...args,fetchImpl:async()=>{
 attempts++;
 return attempts===1?new Response('temporarily unavailable',{status:503}):new Response(JSON.stringify(good),{headers:{'content-type':'application/json'}});
}});
assert.equal(result.ok,true);
assert.equal(attempts,2);
attempts=0;
result=await issueTrustedSandboxFxQuote({...args,fetchImpl:async()=>{
 attempts++;
 return new Response('redirect',{status:302,headers:{location:'https://example.org'}});
}});
assert.equal(result.ok,false);
assert.equal(attempts,1);
console.log('PASS: trusted sandbox FX accepted; invalid source, stale rate and wrong currency rejected');
