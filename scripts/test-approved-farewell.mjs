import {readFileSync,existsSync} from 'node:fs';import assert from 'node:assert/strict';import {createHash} from 'node:crypto';
const html=readFileSync('member-farewell.html','utf8');
const js=readFileSync('member-farewell.js','utf8');
const welcome=readFileSync('member-welcome.js','utf8');
const asset='assets/file_00000000c004820e9861f5922795e822.png';
assert.ok(existsSync(asset),'Founder-approved farewell image must exist');
const bytes=readFileSync(asset);
assert.equal(bytes.subarray(0,8).toString('hex'),'89504e470d0a1a0a','Approved asset must be a real PNG');
assert.ok(bytes.length>10000,'Artwork must not be a placeholder');
const matches=[...html.matchAll(/<img\b[^>]*src="([^"]+)"[^>]*>/g)];
assert.equal(matches.length,1,'Use exactly one approved image, no substitute');
assert.equal(matches[0][1].split('?')[0],'/'+asset,'Approved image source must be exact');
assert.ok(html.includes('object-fit:contain'),'Never crop founder-approved artwork');
assert.ok(!html.includes('opacity:.24'),'Do not darken approved artwork');
assert.ok(!html.includes('linear-gradient(180deg,#210d2acb'),'No dark overlay');
assert.ok(!html.includes('mobile-actions" aria-label'),'No duplicate navigation');
assert.ok(html.includes('id="signout-state"')&&html.includes('id="retry"'),'Keep signout feedback and retry');
assert.ok(js.includes("fetch('/api/member/logout'"),'Farewell must revoke session');
assert.ok(js.includes("verify.status!==401"),'Farewell must verify signed-out state');
assert.ok(js.includes("retry.addEventListener('click',finish)"),'Failure must offer retry');
assert.ok(welcome.includes("location.assign('/member-farewell.html')"),'Signout button must navigate to farewell');
console.log('PASS: approved farewell PNG, full image, no overlay, no duplicate buttons, session-revocation path, retry');
console.log('Artwork SHA256:',createHash('sha256').update(bytes).digest('hex'));
